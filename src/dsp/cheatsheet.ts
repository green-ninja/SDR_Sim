export function filterCheatsheetSections(
  sections: CheatsheetSection[],
  query: string,
  category: 'All' | CheatsheetCategory
): CheatsheetSection[] {
  const trimmed = query.trim().toLowerCase();

  return sections
    .filter((section) => category === 'All' || section.category === category)
    .map((section) => {
      if (!trimmed) return section;
      const matchingEntries = section.entries.filter(
        (entry) =>
          entry.term.toLowerCase().includes(trimmed) ||
          (entry.symbol?.toLowerCase().includes(trimmed) ?? false) ||
          entry.explanation.toLowerCase().includes(trimmed) ||
          entry.practicalNote.toLowerCase().includes(trimmed)
      );
      return { ...section, entries: matchingEntries };
    })
    .filter((section) => section.entries.length > 0);
}
